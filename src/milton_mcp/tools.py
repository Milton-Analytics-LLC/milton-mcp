def load_bundle() -> dict[str, Any]:
    return json.loads(resources.files("milton_mcp").joinpath("schemas.json").read_text())


def build_tools(
    bundle: dict[str, Any], models: dict[str, list[str]], settings: Settings, *, connector: bool = False
) -> list[Tool]:
    envelope = bundle["envelope_schema"]
    tools = [
        _agent_tool(spec, bundle["agents"][spec.agent], models, settings, envelope, connector=connector)
        for spec in AGENT_TOOLS
    ]
    tools.append(
        Tool(
            name=GET_RUN,
            title="Get a Milton run",
            description=(
                "Gets a Milton agent run by its run_id: its status and, once it completes, the same digest "
                "and structured result the tool that started it returns. Waits up to "
                f"{WAIT_SECONDS} seconds for a run that's still working. Use it to follow a desk run or any "
                "run that returned a run_id. Uses no tokens."
            ),
            input_schema={
                "type": "object",
                "properties": {
                    "run_id": {"type": "string", "description": "The run_id a Milton tool returned."},
                },
                "required": ["run_id"],
                "additionalProperties": False,
            },
            output_schema=envelope,
            annotations=ToolAnnotations(title="Get a Milton run", read_only_hint=True),
        )
    )
    return tools


def _agent_tool(
    spec: AgentTool,
    agent: dict[str, Any],
    models: dict[str, list[str]],
    settings: Settings,
    envelope: dict[str, Any],
    *,
    connector: bool = False,
) -> Tool:
    schema = copy.deepcopy(agent["input_schema"])
    props = schema.setdefault("properties", {})
    required = list(schema.get("required", []))

    if not connector:
        model_prop: dict[str, Any] = {
            "type": "string",
            "enum": sorted(models),
            "description": "The model the run uses; its token rates set the cost.",
        }
        if settings.default_model:
            model_prop["default"] = settings.default_model
            model_prop["description"] += f" Defaults to {settings.default_model}."
        else:
            required.append("model")
        props["model"] = model_prop
        props["effort"] = _effort_property(models, settings.default_effort)
    schema["required"] = sorted(required)

    if agent["waits"]:
        returns = (
            "Returns a short digest and the full result as structured content (summary, stance, "
            "conviction, key levels, risks, data as of), with links to the run in Milton. A run still "
            f"working after {WAIT_SECONDS} seconds returns its run_id for milton_get_run instead."
        )
    else:
        returns = (
            "A desk run takes several minutes, so this returns its run_id at once; milton_get_run "
            "returns the result, with a link to the full report, once it completes."
        )
    model = "the model chosen when Milton was connected" if connector else "the chosen model"
    billing = (
        f"The run's tokens (every analyst's, for desk) bill to your Milton balance at {model}'s "
        f"rates ({settings.base_url}/api/v1/pricing)."
    )
    return Tool(
        name=spec.name,
        title=spec.title,
        description=f"{spec.about} {_inputs_sentence(spec.inputs, connector)} {returns} {billing}",
        input_schema=schema,
        output_schema=envelope,
        annotations=ToolAnnotations(title=spec.title, read_only_hint=True),
    )


def _inputs_sentence(fields: tuple[str, ...], connector: bool) -> str:
    """The inputs the tool's schema has: a connector's tools take no model or effort."""
    if connector:
        return f"Inputs: {' and '.join(fields)}." if fields else "Takes no inputs."
    no_ticker = "" if "ticker" in fields else "; no ticker"
    return f"Inputs: {', '.join([*fields, 'model'])} and an optional effort{no_ticker}."


def _effort_property(models: dict[str, list[str]], default_effort: str | None) -> dict[str, Any]:
    offered = {level for levels in models.values() for level in levels}
    ordered = [level for level in EFFORT_ORDER if level in offered]
    ordered += sorted(offered - set(ordered))

    groups: dict[tuple[str, ...], list[str]] = defaultdict(list)
    for model, levels in sorted(models.items()):
        if list(levels) != ordered:
            groups[tuple(levels)].append(model)
    exceptions = "; ".join(f"{', '.join(names)}: {', '.join(levels)}" for levels, names in groups.items())

    description = "Reasoning effort. "
    if default_effort:
        description += f"Defaults to {default_effort}. "
    else:
        description += "Defaults to high, or the model's highest level when it doesn't offer high. "
    if exceptions:
        description += f"Not every model offers every level ({exceptions})."
    prop: dict[str, Any] = {"type": "string", "enum": ordered, "description": description.strip()}
    if default_effort:
        prop["default"] = default_effort
    return prop
